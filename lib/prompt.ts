export function buildUserMessage(input: AuditInput, result: LossResult): string {
  const niche = nicheById(input.niche);
  const method = methodById(input.method);
  const lines = [
    "## Данные клиента",
    `- Ниша: ${niche.label}`,
    `- Способ учёта клиентов и заявок: ${method.label}`,
    `- Заявок в месяц: ${input.leadsPerMonth}`,
    `- Конверсия заявки в заказ: ${input.conversionPct}%`,
    `- Средний чек: ${rub(input.avgCheck)}`,
    `- Маржинальность: ${input.marginPct}%`,
    `- Клиентская база: ${result.clientBaseEstimated ? "нет данных" : input.clientBase}`,
    `- Комментарий клиента: ${input.comment?.trim() || "нет"}`,
    "",
    "## Расчёт потерь (алгоритм сервиса)",
    `- Выручка в месяц: ${rub(result.monthlyRevenue)}, валовая прибыль: ${rub(result.monthlyGrossProfit)}`,
    ...result.items.map((i, n) => `${n + 1}. ${i.title}: ${rub(i.monthlyProfit)} прибыли в месяц (${i.assumption})`),
    `- Итого: ${rub(result.totalMonthly)} в месяц, ${rub(result.totalYearly)} в год`,
    `- Это ${pct(result.shareOfProfit)} валовой прибыли, масштаб: ${result.severity}`,
    "",
    "Составь аудит строго по структуре. Три точки потерь соответствуют трём пунктам расчёта.",
  ];
  return lines.join("\n");
}
